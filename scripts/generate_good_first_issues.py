#!/usr/bin/env python3
"""Write docs/community/GOOD_FIRST_ISSUES.md from the stages that are still stubs (most-used-by-workflows first)."""
from __future__ import annotations

import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).resolve().parent))
import registry_io  # noqa: E402

N = 12


def main() -> None:
    stages = {s["stage_id"]: s for s in registry_io.load_stage_doc(ROOT)["stages"]}
    use = Counter(st["stage"] for w in registry_io.load_workflow_sources(ROOT) for st in w["steps"])
    stubs = sorted((i for i, s in stages.items() if s["status"] == "stub"), key=lambda i: (-use[i], i))[:N]
    out = [
        "# Good first issues (drafts)",
        "",
        "Generated by `python3 scripts/generate_good_first_issues.py`. Items for stages that are still `stub` come first; when none remain, only the verification tasks below are listed.",
        "",
        "Recipe: copy a file from `registry/stage-content/` (for example `099.json`), rewrite every field for the stage, run `make all`.",
        "Rules: at least 4 ordered steps, at least 2 failure modes, a worked example starting with `ILLUSTRATIVE`, and no commands that",
        "point at scripts that do not exist. Do not change stage ids or names.",
        "",
    ]
    for n, sid in enumerate(stubs, 1):
        s = stages[sid]
        out += [
            f"## {n}. Write stage {sid}: {s['stage_name']}",
            f"Accountable role: `{s['raci']['accountable']}`. Used by {use[sid]} workflow(s). Create `registry/stage-content/{sid:03d}.json` with `\"status\": \"complete\"`. "
            "Done when `make all` passes.",
            "",
        ]
    out += [
        f"## {len(stubs) + 1}. Run one eval against a model",
        "Follow `evals/README.md`, save a dated result in `evals/results/`, and open a pull request. Do not edit the case files to make a model pass.",
        "",
        f"## {len(stubs) + 2}. Add a scenario",
        "Add a JSON file in `tests/scenarios/` for a workflow not yet covered. `make test` must pass.",
        "",
        f"## {len(stubs) + 3}. Test one adapter and log it",
        "Install the library into one agent tool listed in `adapters/COMPATIBILITY.md`, run a real task, and attach a dated log. Only then may its status change from \"documented\".",
    ]
    (ROOT / "docs/community/GOOD_FIRST_ISSUES.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote docs/community/GOOD_FIRST_ISSUES.md ({len(stubs)} stage items)")


if __name__ == "__main__":
    main()
