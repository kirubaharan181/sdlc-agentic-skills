#!/usr/bin/env python3
"""Generate derived reports from the registries into dist/ (git-ignored).

Outputs
  dist/SDLC_STAGE_SKILL_MAPPING.csv   one row per stage, derived from the registry
  dist/COVERAGE_REPORT.md             several separate, honestly-defined coverage numbers
  dist/playbooks/<skill-id>.md        per-skill stage playbook, derived from the registry

"Coverage" is deliberately not a single number.  A stage that has a skill ID is *mapped*; that says nothing
about whether it has specific content, a runnable validation command, or a test that exercises it.
"""
from __future__ import annotations

import csv
import io
import json
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import registry_io  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]


def scenario_stage_ids(root: Path) -> set[int]:
    """Stage ids named by machine-readable scenario tests (tests/scenarios/*.json); none exist yet."""
    ids: set[int] = set()
    for p in sorted((root / "tests" / "scenarios").glob("*.json")) if (root / "tests" / "scenarios").is_dir() else []:
        ids |= set(json.loads(p.read_text(encoding="utf-8")).get("stage_ids", []))
    return ids


def metrics(data: dict, root: Path = ROOT) -> dict:
    stages, agents, workflows = data["stages"], data["agents"], data["workflows"]
    used_agents = {a for s in stages for a in s["agents"]}
    wf_sizes = sorted(len(w["stages"]) for w in workflows)
    return {
        "stages_total": len(stages),
        "stages_mapped": sum(1 for s in stages if s["skills"] and s["agents"] and s["quality_gate"]),
        "stages_complete": sum(1 for s in stages if s.get("status") == "complete"),
        "stages_stub": sum(1 for s in stages if s.get("status", "stub") == "stub"),
        "stages_with_validation_commands": sum(1 for s in stages if s.get("validation_commands")),
        "stages_exercised_by_scenario_test": len(scenario_stage_ids(root) & {s["stage_id"] for s in stages}),
        "stages_requiring_approval": sum(1 for s in stages if s["approval_required"]),
        "approval_without_rationale": sum(1 for s in stages if s["approval_required"] and not s.get("approval_rationale")),
        "roles_total": len(agents),
        "roles_assigned_to_a_stage": len(used_agents & {a["agent_id"] for a in agents}),
        "workflows_total": len(workflows),
        "workflow_stage_counts": {"min": wf_sizes[0], "max": wf_sizes[-1]},
        "workflows_with_fewer_than_5_stages": [w["workflow_id"] for w in workflows if len(w["stages"]) < 5],
        "distinct_gate_ids": len({s["quality_gate"] for s in stages}),
    }


def render_csv(stages: list[dict]) -> str:
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(["stage_id", "stage_name", "category_id", "status", "skills", "agents", "workflow_ids", "quality_gate", "approval_required"])
    for s in stages:
        w.writerow([s["stage_id"], s["stage_name"], s["category_id"], s.get("status", "stub"), ";".join(s["skills"]),
                    ";".join(s["agents"]), ";".join(s["workflow_ids"]), s["quality_gate"], str(s["approval_required"]).lower()])
    return buf.getvalue()


def render_coverage(data: dict, root: Path = ROOT) -> str:
    m = metrics(data, root)
    stages = data["stages"]
    n = m["stages_total"]
    pct = lambda x: f"{x} of {n} ({100 * x / n:.0f}%)"
    lines = [
        "# Coverage report",
        "",
        "> Generated by `scripts/generate_reports.py` from the registries. Do not edit.",
        "",
        "| Measure | Value | What it means |",
        "|---|---|---|",
        f"| Stages mapped | {pct(m['stages_mapped'])} | has a skill, an agent and a gate id. Says nothing about quality. |",
        f"| Stages with specific content | {pct(m['stages_complete'])} | `status: complete`: hand-written, stage-specific procedure and acceptance criteria. |",
        f"| Stages still stub | {pct(m['stages_stub'])} | generated template content only. |",
        f"| Stages with validation commands | {pct(m['stages_with_validation_commands'])} | an exact command or check that produces evidence. |",
        f"| Stages exercised by a scenario test | {pct(m['stages_exercised_by_scenario_test'])} | named in a machine-readable scenario under `tests/scenarios/`. |",
        f"| Roles assigned to a stage | {m['roles_assigned_to_a_stage']} of {m['roles_total']} | roles listed in at least one stage's `agents`. |",
        f"| Stages requiring human approval | {m['stages_requiring_approval']} | each needs an `approval_rationale` ({m['approval_without_rationale']} missing). |",
        f"| Workflows | {m['workflows_total']} | sizes {m['workflow_stage_counts']['min']} to {m['workflow_stage_counts']['max']} stages; "
        f"under 5 stages: {', '.join(m['workflows_with_fewer_than_5_stages']) or 'none'}. |",
        "",
        "## By domain",
        "",
        "| Domain | Stages | Complete | Stub | Approval |",
        "|---|---:|---:|---:|---:|",
    ]
    by = Counter()
    for s in stages:
        by[(s["category_id"], s["category_name"], "total")] += 1
        by[(s["category_id"], s["category_name"], s.get("status", "stub"))] += 1
        by[(s["category_id"], s["category_name"], "appr")] += int(s["approval_required"])
    seen = sorted({(c, nme) for c, nme, _ in by})
    for c, nme in seen:
        lines.append(f"| {c:02d} {nme} | {by[(c, nme, 'total')]} | {by[(c, nme, 'complete')]} | {by[(c, nme, 'stub')]} | {by[(c, nme, 'appr')]} |")
    lines += ["", "## Stages by workflow", "", "| Workflow | Stages |", "|---|---:|"]
    lines += [f"| {w['workflow_id']} | {len(w['stages'])} |" for w in data["workflows"]]
    return "\n".join(lines) + "\n"


def render_playbooks(data: dict) -> dict[str, str]:
    out = {}
    for sk in data["skills"]:
        matched = [s for s in data["stages"] if sk["skill_id"] in s["skills"]]
        if not matched:
            continue
        lines = [f"# {sk['skill_id']}: stage playbook", "", "> Generated from the stage registry. Do not edit.", ""]
        for s in matched:
            lines += [f"## {s['stage_id']}. {s['stage_name']}  (`{s.get('status', 'stub')}`)", "", f"**Purpose:** {s['purpose']}", "", "**Procedure:**",
                      *[f"- {x}" for x in s["execution_instructions"]], "", f"**Inputs:** {', '.join(s['inputs'])}",
                      f"**Artifact:** {s['deliverable_artifacts'][0]}", f"**Verification:** {s['validation_method']}",
                      f"**Handoff:** {s['handoff_requirements']}", ""]
        out[sk["skill_id"]] = "\n".join(lines)
    return out


def write_all(root: Path = ROOT) -> list[Path]:
    data = registry_io.load_all(root)
    dist = root / "dist"
    (dist / "playbooks").mkdir(parents=True, exist_ok=True)
    written = []
    for rel, text in {
        "SDLC_STAGE_SKILL_MAPPING.csv": render_csv(data["stages"]),
        "COVERAGE_REPORT.md": render_coverage(data, root),
    }.items():
        (dist / rel).write_text(text, encoding="utf-8")
        written.append(dist / rel)
    for sid, text in render_playbooks(data).items():
        p = dist / "playbooks" / f"{sid}.md"
        p.write_text(text, encoding="utf-8")
        written.append(p)
    return written


if __name__ == "__main__":
    files = write_all(ROOT)
    print(f"generated {len(files)} files under dist/")
