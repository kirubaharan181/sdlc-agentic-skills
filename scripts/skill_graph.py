"""Skill relationships: handoff edges, cycle detection, responsibility uniqueness and generated selection docs.

Source: registry/skill-content/<skill>.json (`handoffs`, `owns`, `keywords`). Nothing here is hand-edited downstream.
A handoff marked `feedback: true` is a rework or learning loop (for example review findings back to implementation);
all other handoffs must form an acyclic graph so work has a defined order.
"""
from __future__ import annotations

from collections import defaultdict


def edges(content: dict[str, dict]) -> list[tuple[str, str, str, bool]]:
    return sorted((src, h["skill"], h["artifact"], bool(h.get("feedback"))) for src, c in content.items() for h in c["handoffs"])


def forward_cycle(content: dict[str, dict]) -> list[str] | None:
    """Return one cycle among non-feedback edges, or None."""
    graph = defaultdict(list)
    for src, dst, _, fb in edges(content):
        if not fb:
            graph[src].append(dst)
    state: dict[str, int] = {}
    stack: list[str] = []

    def visit(n: str) -> list[str] | None:
        state[n] = 1
        stack.append(n)
        for m in sorted(graph[n]):
            if state.get(m) == 1:
                return stack[stack.index(m):] + [m]
            if state.get(m) is None:
                found = visit(m)
                if found:
                    return found
        stack.pop()
        state[n] = 2
        return None

    for n in sorted(content):
        if state.get(n) is None:
            found = visit(n)
            if found:
                return found
    return None


def duplicate_responsibilities(content: dict[str, dict]) -> dict[str, list[str]]:
    owners: dict[str, list[str]] = defaultdict(list)
    for sid, c in content.items():
        for o in c["owns"]:
            owners[o].append(sid)
    return {o: s for o, s in owners.items() if len(s) > 1}


def mermaid(content: dict[str, dict]) -> str:
    ids = {s: s.replace("-", "_") for s in content}
    lines = ["flowchart LR"]
    for s in sorted(content):
        lines.append(f"  {ids[s]}[\"{s}\"]")
    for src, dst, _, fb in edges(content):
        lines.append(f"  {ids[src]} {'-.->' if fb else '-->'} {ids[dst]}")
    return "\n".join(lines)


def render_selection_doc(content: dict[str, dict], stage_ranges: dict[str, str]) -> str:
    out = ["# Skill selection, responsibilities and handoffs", "",
           "Generated by `python3 scripts/build.py` from `registry/skill-content/*.json`. Do not edit by hand.", "",
           "## 1. Choose a skill", "",
           "Use `python3 scripts/select_skill.py \"<request>\"` for a ranked suggestion. It matches words, not meaning, so confirm the result.",
           "Use `master-orchestration` when a request spans several skills. If a request clearly fits one skill, use that skill directly.", "",
           "| If the request is about | Use | Not this (use instead) |", "|---|---|---|"]
    for sid in sorted(content):
        c = content[sid]
        out.append(f"| {c['when_to_use'][0].rstrip('.')} | `{sid}` | {c['when_not_to_use'][0].rstrip('.')} |")
    out += ["", "## 2. Responsibility matrix", "",
            "Each responsibility has exactly one owning skill; `scripts/validate.py` fails on a duplicate.", "",
            "| Skill | Stages | Owns |", "|---|---|---|"]
    for sid in sorted(content):
        out.append(f"| `{sid}` | {stage_ranges.get(sid, 'cross-cutting')} | {', '.join(content[sid]['owns'])} |")
    out += ["", "## 3. Dependency graph", "",
            "Solid arrows are the forward flow and must stay acyclic. Dashed arrows are feedback loops such as rework or learning.", "",
            "```mermaid", mermaid(content), "```", "",
            "## 4. Handoff matrix", "",
            "| From | To | Artifact handed over | Type |", "|---|---|---|---|"]
    for src, dst, art, fb in edges(content):
        out.append(f"| `{src}` | `{dst}` | {art} | {'feedback' if fb else 'forward'} |")
    out += ["", "Each handoff follows [the handoff contract standard](../governance/HANDOFF_CONTRACT_STANDARD.md).", ""]
    return "\n".join(out)
