#!/usr/bin/env python3
"""Write docs/audit/ROLE_DECISIONS.md from the registries (assign / merge / remove decisions, with measured facts)."""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).resolve().parent))
import audit_duplication as dup  # noqa: E402
import registry_io  # noqa: E402

# Documented human decisions. A role listed here as merge/remove must be removed from the registry in the same change.
DECISIONS: dict[str, tuple[str, str]] = {}  # role -> (decision, reason); empty = all roles kept


def main() -> None:
    agents = registry_io.load_agent_doc(ROOT)["agents"]
    owns = {a["agent_id"]: set(a["raci_summary"]["accountable"]) | set(a["raci_summary"]["responsible"]) for a in agents}
    thin = sorted(a["agent_id"] for a in agents if len(owns[a["agent_id"]]) == 1)
    pairs, _ = dup.near_duplicates(ROOT, 0.80, scope=("agents",))
    tiers: dict[str, int] = {}
    for a in agents:
        tiers[a["permission_tier"]] = tiers.get(a["permission_tier"], 0) + 1
    out = [
        "# Role decisions",
        "",
        "Generated by `python3 scripts/generate_role_decisions.py`. Every number is measured from the registries.",
        "",
        "## Outcome",
        f"- Roles: {len(agents)}. Roles owning (accountable or responsible for) at least one stage: {sum(1 for a in agents if owns[a['agent_id']])}. Unassigned: {sum(1 for a in agents if not owns[a['agent_id']])}.",
        "- Baseline (`BASELINE.md`): 60 roles were in no stage's `agents`; 30 were in no stage and no workflow.",
        f"- Decision for every role: **assign** (kept, given a RACI footprint). Merged: {sum(1 for d, _ in DECISIONS.values() if d == 'merge')}. Removed: {sum(1 for d, _ in DECISIONS.values() if d == 'remove')}.",
        f"- Permission tiers: " + ", ".join(f"`{k}` {v}" for k, v in sorted(tiers.items())) + ".",
        "- The audit's claim that `master-orchestration` was a default skill for 60 roles did not hold on current `main` (0 roles had it). The validator now forbids it as a role skill.",
        "",
        "## Why no role was merged or removed",
        "Each role was assigned at least one stage in `registry/SDLC_STAGE_REGISTRY.json` (`raci`), and the near-duplicate",
        "text between role contracts came from shared boilerplate and one profile-matching bug, not from overlapping duties.",
        "The bug: the audit profile pattern `compliance-specialist` also matched `license-compliance-specialist`, so that role",
        "received the audit contract (similarity 0.916 with `security-auditor`). The pattern is now anchored; the pair is below 0.85.",
        "",
        "## Thinly assigned roles (own exactly one stage)",
        "These are kept because each is a distinct accountable function, but they are the first merge candidates if a",
        "maintainer wants fewer roles. Revisit once Phase 4 content shows whether a one-stage role carries real procedure.",
        "",
        *(f"- `{r}` (stage {sorted(owns[r])[0]})" for r in thin),
        "",
        f"## Role contract pairs at or above 0.80 similarity ({len(pairs)})",
        "Measured with `scripts/audit_duplication.py` (names stripped). The validator fails at 0.85.",
        "",
        "| Similarity | Role A | Role B | Stages owned in common |",
        "|---|---|---|---|",
    ]
    for a, b, r in pairs:
        ia, ib = Path(a).stem, Path(b).stem
        out.append(f"| {r:.3f} | `{ia}` | `{ib}` | {len(owns.get(ia, set()) & owns.get(ib, set()))} |")
    out += ["", "Pairs with no stage in common keep separate roles: they act on different artifacts at different points of the lifecycle.", ""]
    (ROOT / "docs/audit/ROLE_DECISIONS.md").write_text("\n".join(out), encoding="utf-8")
    print("wrote docs/audit/ROLE_DECISIONS.md")


if __name__ == "__main__":
    main()
